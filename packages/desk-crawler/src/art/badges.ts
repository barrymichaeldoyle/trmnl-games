/** `slay_paper_imp` to the paper imp's sprite. */
const monsterOf = (family: string): Sprite | null => (family.startsWith('slay_') ? ((monsterArt as Record<string, Sprite>)[family.slice('slay_'.length)] ?? null) : null)

/** Whether a family has a badge: a picture, or a monster with a sprite. */
export const hasBadge = (family: string): boolean => monsterOf(family) !== null || family in BADGE_PICTURES

/**
 * The medallion's layers for a family at 40 pixels: its picture or its monster; locked, the "?". On the device
 * (`cutout`) the top tier cuts a picture out of its solid disc and gives a monster a paper window.
 */
export function badgeLayers(family: string, frame: BadgeFrame, cutout = true): BadgeLayers {
  const monster = monsterOf(family)
  if (frame === 0) return medallion(BADGE_SIZE, LOCKED, 0, { cutout })
  const art = monster ? monster.rows : ((BADGE_PICTURES as Record<string, readonly string[]>)[family] ?? [])
  return medallion(BADGE_SIZE, art, frame, { cutout, creature: monster !== null })
}

/** The 1-bit medallion for the device. */
export const badgeCanvas = (family: string, frame: BadgeFrame): Canvas => drawBadge(badgeLayers(family, frame))

/** The badge in the companion's colours: picture and monster in ink on the disc; the "?" in the locked tone. */
export const badgeColourLayers = (family: string, frame: BadgeFrame): ReadonlyArray<{ readonly sprite: Sprite; readonly tones: BadgeTones }> => paint(badgeLayers(family, frame, false), frame)

/** How many tiers each family has in the current catalog. */
const TIER_COUNTS: ReadonlyMap<string, number> = ACHIEVEMENTS.reduce((counts, a) => counts.set(a.family, Math.max(counts.get(a.family) ?? 0, a.tier)), new Map<string, number>())

/** A family's last tier wears the top frame; the tiers before it climb copper, silver, gold and sky. */
export const frameForTier = (family: string, tier: number): BadgeFrame => frameOf(tier, TIER_COUNTS.get(family) ?? 5)

/** The six badges a public profile shows: finished families, then the rarest, then the higher tier. */
export function showcaseBadges(unlocked: readonly string[], counts: Readonly<Record<string, number>> | null = null): Array<{ family: string; tier: number; id: string }> {
  const earned = unlocked.flatMap((id) => {
    const def = ACHIEVEMENT_BY_ID.get(id)
    return def ? [{ family: def.family, tier: def.tier, id }] : []
  })
  return showcase(earned, (b) => frameForTier(b.family, b.tier), counts)
}
