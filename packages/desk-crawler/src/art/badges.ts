/** A picture's rows with '.' as transparent, trimmed to its ink so the medallion centres what is drawn, not the grid. */
function picture(grid: readonly string[]): readonly string[] {
  const rows = grid.map((row) => row.replaceAll('.', ' '))
  const inked = (row: string) => row.trim() !== ''
  const top = rows.findIndex(inked)
  const bottom = rows.length - [...rows].reverse().findIndex(inked)
  const kept = rows.slice(top, bottom)
  const left = Math.min(...kept.filter(inked).map((row) => row.search(/\S/)))
  const right = Math.max(...kept.map((row) => row.trimEnd().length))
  return kept.map((row) => row.slice(left, right))
}

