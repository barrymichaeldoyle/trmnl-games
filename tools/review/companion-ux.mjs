/** D226: real companion components with synthetic state; no backend or player mutations.
 * Run companion-fixtures.mjs and its Vite server first, then node tools/review/companion-ux.mjs.
 */
import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const origin = process.argv[2] ?? 'http://127.0.0.1:4197'
const browser = await chromium.launch({ channel: 'chrome' })
let checks = 0
const check = (ok, message) => { assert.ok(ok, message); console.log('ok', message); checks++ }
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const goto = async (path) => { await page.goto(origin + path); await page.locator('main h1').waitFor() }
  for (const lang of ['en', 'fr', 'de', 'es', 'it', 'pt', 'pl', 'nl']) {
    await goto(`/app/idle-angler/cooler?signedout=1&lang=${lang}`)
    check(await page.getByRole('heading', { name: 'Idle Angler', exact: true }).count() === 1, `${lang}: game-aware entry`)
    const mainLinks = await page.locator('main a').evaluateAll((links) => links.map((a) => a.getAttribute('href')))
    check(mainLinks.includes('https://trmnl.com/integrations/idle-angler') && !mainLinks.some((href) => href?.includes('desk-crawler')), `${lang}: correct installation and guide`)
    check(await page.locator('header nav a[href^="/help/idle-angler"]').count() === 1, `${lang}: contextual header help`)
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${lang}: entry fits phone`)
  }
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-entry-mobile.png' })
  await goto('/app/idle-angler/cooler?v2=1&ia=full')
  await page.getByRole('button', { name: 'Sell catch', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const include = dialog.getByRole('checkbox', { name: 'Include trophy-size fish' })
  check(!await include.isChecked(), 'bulk review excludes trophies by default')
  await dialog.getByRole('button', { name: /^Sell for /i }).click()
  await dialog.getByRole('alert').waitFor({ state: 'visible' })
  check(await dialog.isVisible(), 'failed sale stays open with inline error')
  const attempts = await page.evaluate(() => window.__mutations.filter((m) => m.fn === 'idleAngler/anglers:sellCatches'))
  check(attempts.at(-1).args.catchIds.length === 17, 'bulk payload excludes the trophy specimen')
  await dialog.getByRole('button', { name: /^Sell for /i }).click()
  await page.waitForTimeout(1500)
  const retries = await page.evaluate(() => window.__mutations.filter((m) => m.fn === 'idleAngler/anglers:sellCatches'))
  check(retries.length === 2 && retries[0].args.operationId === retries[1].args.operationId, 'retry retains the same operation identity')
  await include.check()
  check(await dialog.getByText(/cannot be mounted afterwards/).isVisible(), 'explicit trophy inclusion shows consequences')
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-sale-review-mobile.png' })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.locator('main input[type="checkbox"]').nth(1).check()
  await page.evaluate(() => scrollTo(0, 0))
  const sale = page.getByRole('button', { name: 'Sell 1', exact: true })
  const box = await sale.boundingBox()
  check(box.y >= 0 && box.y + box.height <= 844, 'selected-sale button stays in the viewport at top of long cooler')
  await sale.click()
  await page.getByRole('alert').filter({ hasText: /could not confirm/ }).waitFor()
  const alertBox = await page.getByRole('alert').filter({ hasText: /could not confirm/ }).boundingBox()
  check(alertBox.y + alertBox.height <= (await sale.boundingBox()).y, 'error notice stays above selection bar')
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-selection-mobile.png' })
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  check(await page.getByRole('button', { name: 'Sell 1', exact: true }).count() === 0, 'clear selection removes sale bar')
  await page.getByRole('button', { name: /^Mount /i }).first().click()
  await dialog.getByRole('button', { name: /^Mount for/i }).click()
  await dialog.getByRole('alert').waitFor({ state: 'visible' })
  check(await dialog.isVisible(), 'failed mounting retains confirmation')
  await goto('/app/idle-angler/cooler?v2=1&trophy=all')
  await page.getByRole('button', { name: 'Sell catch', exact: true }).click()
  check(await dialog.getByRole('button', { name: /^Sell for /i }).isDisabled(), 'all-trophy cooler cannot accidentally submit an empty sale')
  await dialog.getByRole('checkbox').check()
  check(!await dialog.getByRole('button', { name: /^Sell for /i }).isDisabled(), 'explicit inclusion allows all-trophy sale')
  await goto('/app/idle-angler/cooler?v2=1&trophy=bait')
  await page.getByRole('button', { name: 'Use as bait', exact: true }).first().click()
  check(await dialog.getByText(/cannot be mounted afterwards/).isVisible(), 'trophy bait conversion asks first')
  check(await page.evaluate(() => (window.__mutations ?? []).length === 0), 'opening trophy-bait review does not consume fish')
  await goto('/app/idle-angler/shop?v2=1')
  await page.getByRole('button', { name: /^Buy /i }).first().click()
  await dialog.getByRole('button', { name: /^Buy for/i }).click()
  await dialog.getByRole('alert').waitFor({ state: 'visible' })
  check(await dialog.isVisible(), 'failed purchase retains confirmation')
  await goto('/app/idle-angler/settings?v2=1')
  await page.getByRole('button', { name: /^Pause/i }).first().click()
  await dialog.getByRole('button', { name: /^Pause/i }).click()
  await dialog.getByRole('alert').waitFor({ state: 'visible' })
  check(await dialog.isVisible(), 'failed pause retains confirmation')
  await goto('/app/idle-angler/trophies?v2=1')
  await page.getByRole('button', { name: 'Take down', exact: true }).first().click()
  await dialog.getByRole('button', { name: 'Take down', exact: true }).click()
  await dialog.getByRole('alert').waitFor({ state: 'visible' })
  check(await dialog.isVisible(), 'failed trophy removal retains confirmation')
  await goto('/app/idle-angler/cooler?v2=1&ok=1')
  await page.getByRole('button', { name: 'Sell catch', exact: true }).click()
  await dialog.getByRole('button', { name: /^Sell for /i }).click()
  await dialog.waitFor({ state: 'hidden' })
  check(await page.getByRole('status').filter({ hasText: /^Sold / }).isVisible(), 'successful sale closes review and announces completion')
  for (const state of ['full', 'empty', 'paused']) {
    await goto(`/app/idle-angler?v2=1&ia=${state}&whatsnew=1`)
    const scene = page.locator('main img[alt*="fishing at"]')
    await scene.waitFor()
    const sceneBox = await scene.boundingBox()
    if (state === 'full') check((await page.locator('p').filter({ hasText: /^The cooler is full/ }).boundingBox()).y < sceneBox.y, 'full-cooler warning precedes scene')
    if (state === 'empty') check((await page.locator('p').filter({ hasText: /^You have no bait|^Your angler is fishing a bare hook/ }).boundingBox()).y < sceneBox.y, 'bare-hook warning precedes scene')
    if (state === 'paused') check(await page.locator('p').filter({ hasText: /^You have no bait|^Your angler is fishing a bare hook/ }).count() === 0, 'paused angler is not described as fishing a bare hook')
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${state}: Dock fits phone`)
  }
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-dock-mobile.png' })
  await page.setViewportSize({ width: 1280, height: 900 })
  await goto('/app/idle-angler?v2=1&ia=full&whatsnew=1')
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-dock-desktop.png' })
  // A narrower viewport and longer labels exercise wrapping and the measured selection spacer.
  await page.setViewportSize({ width: 320, height: 740 })
  await goto('/app/idle-angler/cooler?v2=1&ia=full&lang=de')
  await page.locator('main input[type="checkbox"]').nth(1).check()
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'German selection fits narrow phone')
  await page.screenshot({ animations: 'disabled', path: '.previews/ux-selection-de.png' })
  console.log(`${checks} companion UX checks passed; only synthetic mutations were exercised.`)
} finally { await browser.close() }
