const plural = (n: number, one: string, many: string) => (n === 1 ? one : many)
const capital = (text: string) => text.charAt(0).toUpperCase() + text.slice(1)
const signed = (value: number) => (value > 0 ? `+${value}` : `−${Math.abs(value)}`)

type Layout = 'markup' | 'markup_half_horizontal' | 'markup_half_vertical' | 'markup_quadrant'
type Numbers = { hpPct: number; attackPct?: number; defensePct?: number; goldPct?: number; raidEdgePct: number }

/** "Health 85% · Attack +10% · …" from labels, so each language keeps the class's numbers in one line. */
const classLine = (n: Numbers, words: { health: string; attack: string; defense: string; gold: string; raids: (v: string) => string; full: string }, pct: (v: string) => string) => {
  const parts: string[] = []
  if (n.hpPct !== 100) parts.push(`${words.health} ${pct(String(n.hpPct))}`)
  if (n.attackPct) parts.push(`${words.attack} ${pct(signed(n.attackPct))}`)
  if (n.defensePct) parts.push(`${words.defense} ${pct(signed(n.defensePct))}`)
  if (n.goldPct) parts.push(`${words.gold} ${pct(signed(n.goldPct))}`)
  if (n.raidEdgePct) parts.push(words.raids(signed(n.raidEdgePct)))
  return parts.length === 0 ? words.full : parts.join(' · ')
}

