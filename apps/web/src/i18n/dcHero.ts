const plural = (n: number, one: string, many: string) => (n === 1 ? one : many)
/** D216: "A, B and C", or "A, B, C and 8 others" when `more` names the rest. */
const company = (and: string, more: (k: number) => string) => (names: readonly string[], others: number) => {
  const rest = others - names.length
  if (rest > 0) return `${names.join(', ')} ${more(rest)}`
  return names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} ${and} ${names[names.length - 1]}`
}

