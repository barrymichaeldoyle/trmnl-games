/** The article or possessive before a name in a phrase ("tu ", "la tua "), so the name itself can be marked up apart. */
const lead = (c: ContentTranslator, english: string, form: string) => {
  const name = c.name(english)
  const phrase = c.nameWith(english, form)
  return phrase.endsWith(name) ? phrase.slice(0, phrase.length - name.length) : ''
}
